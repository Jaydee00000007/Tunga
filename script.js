const meals = [restA, restB, restC, restD, restE, restF, restG, restH];

let currentRestaurantIndex = 0;
let currentMenu = meals[0] || [];
let cart = [];









const cartBtn = document.querySelector('.cart');
const closeBtn = document.querySelector('.close-btn');
const cartSidebar = document.querySelector('.cart-sidebar');
const foodMenu = document.querySelector('.menu');
const openMenus = document.querySelectorAll('.open-menu');
const closeMenu = document.querySelector('.close-menu');
// const restMeal = document.getElementById('fd-s');
const restMeal = document.querySelector('.rmenu');
const cartItemsContainer = document.getElementById('cart-items');
const cartCountElement = document.getElementById('cart-count') || document.querySelector('.count');
const cartTotalElement = document.getElementById('cart-total');


cartBtn.addEventListener('click', () => cartSidebar.classList.add('open'));
closeBtn.addEventListener('click', () => cartSidebar.classList.remove('open'));

openMenus.forEach((menu, index) => {
    menu.addEventListener('click', () => {
        currentRestaurantIndex = index;
        currentMenu = meals[index] || [];

        // Use the clicked restaurant's heading text as the menu title
        const restName = menu.textContent.trim();
        const header = document.querySelector('.menu .menu-header h5');
        if (header) header.textContent = restName ? `${restName} — MENU` : 'MENU';

        // Display the meals for this restaurant (meals is an array of arrays)
        displayMenus(currentMenu);

        foodMenu.classList.add('open');
    });
});
closeMenu.addEventListener('click',() => foodMenu.classList.remove('open'));

// Delegate add-to-cart button clicks from the restaurant menu container
restMeal.addEventListener('click', (e) => {
    const btn = e.target.closest('.add-to-cart-btn');
    if (!btn) return;
    const id = btn.dataset.id || btn.getAttribute('data-id');
    if (id) addToCart(Number(id));
});


function displayMenus(mealsArray) {
    restMeal.innerHTML = ""; 
    (mealsArray || []).forEach(meal => {
        const menuItem = document.createElement('div');
        menuItem.classList.add('product-card');
        menuItem.innerHTML = `
            <div class="fdimage"><img src="${meal.img || 'images/default-food.jpg'}" alt="${meal.name}"></div>
            <div class="fname">${meal.name}</div>
            <span class="fprice">N${(meal.price || 0).toFixed(2)}</span>
            <div class="addbtn"><button class="add-to-cart-btn" data-id="${meal.id}">Add to cart</button></div>
        `;
        // attach dataset id for event delegation
        menuItem.dataset.id = meal.id;
        restMeal.appendChild(menuItem);
    });

    // (click delegation handled once outside to avoid adding multiple listeners)
}

// show first restaurant by default
displayMenus(meals[0] || []);


function addToCart(mealsId) {
    const productObj = currentMenu.find(p => p.id === mealsId);
    if (!productObj) {
        console.warn('Could not find product for id', mealsId, 'in current restaurant menu');
        return;
    }

    const itemKey = `${currentRestaurantIndex}-${productObj.id}`;
    const existingItem = cart.find(item => item.key === itemKey);

    if (existingItem) {
        existingItem.quantity += 1;
    } else {
        cart.push({
            key: itemKey,
            restaurantIndex: currentRestaurantIndex,
            ...productObj,
            quantity: 1
        });
    }
    updateCartUI();
}


function changeQuantity(productId, amount) {
    const targetItem = cart.find(item => item.id === productId);
    if (!targetItem) return;

    targetItem.quantity += amount;

    // Completely strip out elements that drop to zero or fewer items
    if (targetItem.quantity <= 0) {
        cart = cart.filter(item => item.id !== productId);
    }
    updateCartUI();
}

function removeFromCart(productId) {
    cart = cart.filter(item => item.id !== productId);
    updateCartUI();
}


function updateCartUI() {
    cartItemsContainer.innerHTML = "";
    let totalItemCount = 0;
    let totalPriceSum = 0;

    cart.forEach(item => {
        totalItemCount += item.quantity;
        totalPriceSum += item.price * item.quantity;

        const cartItemRow = document.createElement('div');
        cartItemRow.classList.add('cart-item');
        cartItemRow.innerHTML = `
            <div class="cart-item-details">
                <h4>${item.name}</h4>
                <p>$${(item.price * item.quantity).toFixed(2)}</p>
            </div>
            <div class="quantity-controls">
                <button onclick="changeQuantity(${item.id}, -1)">-</button>
                <span>${item.quantity}</span>
                <button onclick="changeQuantity(${item.id}, 1)">+</button>
                <button class="remove-btn" onclick="removeFromCart(${item.id})">🗑️</button>
            </div>
        `;
        cartItemsContainer.appendChild(cartItemRow);
    });

    // Write updated quantities and subtotal calculations directly to DOM targets
    cartCountElement.textContent = totalItemCount;
    cartTotalElement.textContent = totalPriceSum.toFixed(2);
}

// Kick off display on script loading execution
updateCartUI();
